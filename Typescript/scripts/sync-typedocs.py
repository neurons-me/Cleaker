# Keeps the VitePress site (Typescript/typedocs) in step with the canonical pages in docs/en (the .GUI site).
# Run from Typescript/: python3 scripts/sync-typedocs.py   then: npm run docs:publish (typedoc + vitepress build).
# Each synced page says where its canonical copy lives; live demos (.GUI widgets) become a link to it; the inline
# SVG diagrams stay; .GUI card grids become plain link lists; links between synced pages stay inside this site.
import os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))          # Typescript/
DOCS = os.path.join(os.path.dirname(ROOT), "docs", "en")
OUT = os.path.join(ROOT, "typedocs")
CANON = "https://neurons-me.github.io/Cleaker/docs/en/"
PAGES = {  # docs/en source -> typedocs page
    "Cleaker": "Cleaker", "The-Model": "The-Model", "The-Algebra-of-Me": "Algebra-of-Me",
    "The-Flat-Universe": "The-Flat-Universe", "Statuses": "Statuses", "Notes": "Notes",
}
LIVE = {"AxIdentity": "Ax1", "AxLocation": "Ax4", "AxAuthority": "Ax5", "QrStatuses": "every QR.me status"}

def link(m):
    text, target = m.group(1), m.group(2)
    t = re.sub(r"^(\./|\.\./en/)", "", target)
    name, _, frag = t.partition("#")
    name = name[:-5] if name.endswith(".html") else name
    if name in PAGES and not target.startswith("http"):
        return f"[{text}](./{PAGES[name]}.html{'#' + frag if frag else ''})"
    if target.startswith("../es/"):
        return f"[{text}](https://neurons-me.github.io/Cleaker/docs/es/{target[6:]})"
    return m.group(0)

def cards(m):
    out = []
    for a in re.finditer(r'<a class="card" href="([^"]+)">.*?<span class="card-title">(.*?)</span><span class="card-desc">(.*?)</span></a>', m.group(0), re.S):
        out.append(f"- [{a.group(2)}]({a.group(1)}): {a.group(3)}")
    return "\n".join(out)

for src, dst in PAGES.items():
    s = open(os.path.join(DOCS, src + ".md")).read()
    s = re.sub(r"\A---\n.*?\n---\n", "", s, count=1, flags=re.S)
    canon = f"{CANON}{src}.html"
    s = re.sub(r'<div data-live="(\w+)"></div>',
               lambda m: f"> **Live:** {LIVE.get(m.group(1), 'this demo')} runs in the browser on the [canonical page]({canon}).", s)
    s = re.sub(r'<div class="doc-cards" markdown="0">.*?</div>', cards, s, flags=re.S)
    s = s.replace(' markdown="0"', "")
    s = re.sub(r"<!-- /?diagram:\w+ -->\n?", "", s)
    s = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", link, s)
    head = (f"<!-- Generated by scripts/sync-typedocs.py from docs/en/{src}.md; edit that file, not this one. -->\n\n")
    title_end = s.index("\n", s.index("# ")) + 1
    s = head + s[:title_end] + f"\n*Canonical page, with its live parts: [{CANON}{src}.html]({canon})*\n" + s[title_end:]
    open(os.path.join(OUT, dst + ".md"), "w").write(s)
    print("synced", src, "->", dst + ".md")
